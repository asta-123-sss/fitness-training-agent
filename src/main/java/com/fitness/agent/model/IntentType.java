package com.fitness.agent.model;

/**
 * 用户输入的意图分类：训练规划请求 或 日常聊天。
 * 由 ChatAgent 在流水线入口判定，决定走「训练计划」还是「直接聊天回复」。
 */
public enum IntentType {

    /** 训练规划请求：描述身体状况、训练目标、想练部位等，走完整规划流水线。 */
    PLAN,

    /** 日常聊天：问候、闲聊、与健身训练无关的内容，直接友好回复。 */
    CHAT,

    /** 健身/营养知识问答：期望得到直接解答（而非训练计划），直接专业回复。 */
    QNA
}
